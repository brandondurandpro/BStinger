package org.example.kotlineditor.state

import java.nio.file.Path

/** The shells the `ide` command is written for: what its script is made of depends on the operating system. */
enum class ShellFlavor {
    Posix,
    MacOs,
    Windows,
    ;

    companion object {
        fun current(): ShellFlavor {
            val system = System.getProperty("os.name").orEmpty().lowercase()
            return when {
                system.startsWith("windows") -> Windows
                system.startsWith("mac") -> MacOs
                else -> Posix
            }
        }
    }
}

/** The first comment of every script the IDE writes: a file without it is not ours and is never overwritten. */
internal const val SCRIPT_MARKER = "Generated by Kotlin Editor"

/**
 * The text of the `ide` command. The folder is always made absolute by the shell of the caller, before the IDE
 * starts: the launcher of the packaged app does not run in the directory the command was typed in.
 */
internal object CommandScripts {
    private const val POSIX_FOLDER =
        """folder=${'$'}(CDPATH= cd -- "${'$'}{1:-.}" 2>/dev/null && pwd -P) || { echo "ide: not a directory: ${'$'}{1:-.}" >&2; exit 2; }"""

    private const val GIT_BASH_FOLDER =
        """folder=${'$'}(CDPATH= cd -- "${'$'}{1:-.}" 2>/dev/null && pwd -W) || { echo "ide: not a directory: ${'$'}{1:-.}" >&2; exit 2; }"""

    // One log per user: a file left in /tmp by another user would make the redirection fail.
    private const val LOG = """"${'$'}{TMPDIR:-/tmp}/kotlin-editor-ide-${'$'}(id -u).log""""

    /** The script for Linux and macOS (`open -n` there, or the running app would drop the folder). */
    fun posix(flavor: ShellFlavor, launcher: Path): String {
        val start =
            if (flavor == ShellFlavor.MacOs) {
                val bundle = appBundleOf(launcher)
                "open -n -a ${quoted(bundle.toString())} --args --open \"\$folder\""
            } else {
                "nohup ${quoted(launcher.toString())} --open \"\$folder\" >$LOG 2>&1 &"
            }
        return lines("#!/bin/sh", "# $SCRIPT_MARKER", POSIX_FOLDER, start)
    }

    /** `ide.cmd`: the PATH of cmd.exe and PowerShell. */
    fun windowsCmd(launcher: Path): String {
        // No parenthesized block: a `)` in a folder name would end it. No pushd: it maps a drive for a network path.
        // chcp 65001: cmd reads this file in the code page of the console, and the path of the launcher is UTF-8.
        // A trailing backslash (C:\) would escape the closing quote of the argument.
        // `start`: a batch file waits for the end of a program with a window otherwise.
        // Known limit: `start` hands every handle of the caller to the IDE, redirections or not (cmd keeps the
        // originals inheritable): a program that reads the output of `ide` to its end waits for the IDE to exit.
        val text =
            """
            @echo off
            rem $SCRIPT_MARKER
            setlocal
            for /f "tokens=2 delims=:" %%a in ('chcp') do set "OLDCP=%%a"
            chcp 65001 >nul
            set "FOLDER=%CD%"
            if not "%~1"=="" set "FOLDER=%~f1"
            if not exist "%FOLDER%\" goto bad
            if "%FOLDER:~-1%"=="\" set "FOLDER=%FOLDER%."
            start "" "$launcher" --open "%FOLDER%"
            chcp %OLDCP% >nul
            exit /b 0
            :bad
            echo ide: not a directory: %FOLDER% 1>&2
            chcp %OLDCP% >nul
            exit /b 2
            """.trimIndent() + "\n"
        return text.replace("\n", "\r\n")
    }

    /** `ide` next to `ide.cmd`: the same command in Git Bash, which writes Windows paths with `pwd -W`. */
    fun windowsGitBash(launcher: Path): String {
        val program = quoted(launcher.toString().replace('\\', '/'))
        val start = "nohup $program --open \"\$folder\" >/dev/null 2>&1 &"
        return lines("#!/bin/sh", "# $SCRIPT_MARKER", GIT_BASH_FOLDER, start)
    }

    // Inside a Mac bundle the launcher is Kotlin Editor.app/Contents/MacOS/Kotlin Editor; `open` wants the bundle.
    private fun appBundleOf(launcher: Path): Path {
        var candidate: Path? = launcher
        while (candidate != null) {
            val name = candidate.fileName?.toString().orEmpty()
            if (name.endsWith(".app")) return candidate
            candidate = candidate.parent
        }
        return launcher
    }

    private fun quoted(text: String): String = "'" + text.replace("'", "'\\''") + "'"

    private fun lines(vararg lines: String): String = lines.joinToString("\n", postfix = "\n")
}
